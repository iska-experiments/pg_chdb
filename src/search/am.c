/*
 * Logs a ClickHouse statement at DEBUG1, so tests can assert on what was
 * generated with client_min_messages = debug1. With mask_oids, index OIDs and
 * transaction ids become N, as they differ from run to run.
 */
void
chdb_search_log_sql(const char* what, const char* sql) {
    StringInfoData buf;

    if (!chdb_search_mask_oids) {
        elog(DEBUG1, "chdb_search %s: %s", what, sql);
        return;
    }
    initStringInfo(&buf);
    for (const char* p = sql; *p;) {
        if (strncmp(p, "idx_", 4) == 0 || strncmp(p, "_tx_", 4) == 0) {
            appendBinaryStringInfo(&buf, p, 4);
            p += 4;
            if (isdigit((unsigned char)*p)) {
                while (isdigit((unsigned char)*p)) {
                    p++;
                }
                appendStringInfoChar(&buf, 'N');
            }
        } else {
            appendStringInfoChar(&buf, *p++);
        }
    }
    elog(DEBUG1, "chdb_search %s: %s", what, buf.data);
}

void
_PG_init(void) {
    DefineCustomIntVariable(
        "chdb_search.flush_threshold",
        "Bytes of insert buffer per index above which a transaction stages rows in "
        "ClickHouse.",
        NULL,
        &chdb_search_flush_threshold_kb,
        64 * 1024,
        64,
        MAX_KILOBYTES,
        PGC_USERSET,
        GUC_UNIT_KB,
        NULL,
        NULL,
        NULL
    );
    DefineCustomRealVariable(
        "chdb_search.vacuum_optimize_ratio",
        "Fraction of dead index entries above which VACUUM runs OPTIMIZE TABLE FINAL.",
        NULL,
        &chdb_search_vacuum_optimize_ratio,
        0.2,
        0.0,
        1.0,
        PGC_USERSET,
        0,
        NULL,
        NULL,
        NULL
    );
    DefineCustomBoolVariable(
        "chdb_search.mask_oids",
        "Replace OIDs and transaction ids in logged ClickHouse statements by N, for "
        "tests.",
        NULL,
        &chdb_search_mask_oids,
        false,
        PGC_USERSET,
        0,
        NULL,
        NULL,
        NULL
    );
    MarkGUCPrefixReserved("chdb_search");

    chdb_search_init_options();
    chdb_search_init_insert();
    chdb_search_init_drop();
}

/*
 * The planner asks what a scan costs before it knows the query is cheap in
 * ClickHouse. A search qual is a round trip plus a result proportional to the
 * matches, which are streamed without touching index pages, so the generic
 * page cost is scaled down; an unqualified scan stays at the generic cost.
 */
static void
chdb_search_costestimate(
    PlannerInfo* root,
    IndexPath* path,
    double loop_count,
    Cost* indexStartupCost,
    Cost* indexTotalCost,
    Selectivity* indexSelectivity,
    double* indexCorrelation,
    double* indexPages
) {
    GenericCosts costs = { 0 };

    genericcostestimate(root, path, loop_count, &costs);

    if (path->indexclauses != NIL) {
        costs.indexStartupCost += random_page_cost;
        costs.indexTotalCost = costs.indexStartupCost +
                               0.1 * (costs.indexTotalCost - costs.indexStartupCost);
    }
    *indexStartupCost = costs.indexStartupCost;
    *indexTotalCost   = costs.indexTotalCost;
    *indexSelectivity = costs.indexSelectivity;
    *indexCorrelation = costs.indexCorrelation;
    *indexPages       = costs.numIndexPages;
}

/*
 * Validates an operator class: strategies 1..5, boolean search operators,
 * float8 ordering operators, and at most the options support function. The
 * columnar_ops class is declared for anyelement, its operators of concrete
 * types live in its family, so only the family is checked for contents.
 */
static bool
chdb_search_validate(Oid opclassoid) {
    bool result = true;
    HeapTuple classtup;
    Form_pg_opclass classform;
    Oid opfamilyoid, opcintype;
    char *opclassname, *opfamilyname;
    CatCList *proclist, *oprlist;

    classtup = SearchSysCache1(CLAOID, ObjectIdGetDatum(opclassoid));
    if (!HeapTupleIsValid(classtup)) {
        elog(ERROR, "cache lookup failed for operator class %u", opclassoid);
    }
    classform    = (Form_pg_opclass)GETSTRUCT(classtup);
    opfamilyoid  = classform->opcfamily;
    opcintype    = classform->opcintype;
    opclassname  = pstrdup(NameStr(classform->opcname));
    opfamilyname = get_opfamily_name(opfamilyoid, false);

    oprlist  = SearchSysCacheList1(AMOPSTRATEGY, ObjectIdGetDatum(opfamilyoid));
    proclist = SearchSysCacheList1(AMPROCNUM, ObjectIdGetDatum(opfamilyoid));

    for (int i = 0; i < proclist->n_members; i++) {
        Form_pg_amproc procform =
            (Form_pg_amproc)GETSTRUCT(&proclist->members[i]->tuple);

        if (procform->amprocnum != 1) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains function %s with invalid support number "
                    "%d",
                    opfamilyname,
                    format_procedure(procform->amproc),
                    procform->amprocnum
                )
            );
            result = false;
        } else if (
            procform->amproclefttype == opcintype &&
            !check_amoptsproc_signature(procform->amproc)
        ) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains function %s with wrong signature for "
                    "support number 1",
                    opfamilyname,
                    format_procedure(procform->amproc)
                )
            );
            result = false;
        }
    }

    for (int i = 0; i < oprlist->n_members; i++) {
        Form_pg_amop oprform = (Form_pg_amop)GETSTRUCT(&oprlist->members[i]->tuple);
        bool ordering        = oprform->amoppurpose == AMOP_ORDER;

        if (oprform->amopstrategy < 1 || oprform->amopstrategy > 5) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains operator %s with invalid strategy "
                    "number %d",
                    opfamilyname,
                    format_operator(oprform->amopopr),
                    oprform->amopstrategy
                )
            );
            result = false;
        }
        if (ordering != OidIsValid(oprform->amopsortfamily)) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains invalid ORDER BY specification for "
                    "operator %s",
                    opfamilyname,
                    format_operator(oprform->amopopr)
                )
            );
            result = false;
        }
        if (!check_amop_signature(
                oprform->amopopr,
                ordering ? FLOAT8OID : BOOLOID,
                oprform->amoplefttype,
                oprform->amoprighttype
            )) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains operator %s with wrong signature",
                    opfamilyname,
                    format_operator(oprform->amopopr)
                )
            );
            result = false;
        }
    }

    if (oprlist->n_members == 0) {
        ereport(
            INFO,
            errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
            errmsg("chdb operator class %s has no operators in its family", opclassname)
        );
        result = false;
    }

    ReleaseCatCacheList(proclist);
    ReleaseCatCacheList(oprlist);
    ReleaseSysCache(classtup);
    return result;
}

Datum
chdb_search_handler(PG_FUNCTION_ARGS) {
    IndexAmRoutine* am = makeNode(IndexAmRoutine);

    /* No fixed strategy set: each operator class numbers its own. */
    am->amstrategies            = 0;
    am->amsupport               = 1; /* options */
    am->amoptsprocnum           = 1;
    am->amcanorder              = false;
    am->amcanorderbyop          = true; /* distance order-bys, from chdb_vector */
    am->amcanbackward           = false;
    am->amcanunique             = false;
    am->amcanmulticol           = true;
    am->amoptionalkey           = true;
    am->amsearcharray           = false;
    am->amsearchnulls           = false;
    am->amstorage               = false;
    am->amclusterable           = false;
    am->ampredlocks             = false;
    am->amcanparallel           = false;
    am->amcanbuildparallel      = false;
    am->amcaninclude            = false;
    am->amusemaintenanceworkmem = false;
    am->amsummarizing           = false;
    am->amparallelvacuumoptions = 0;
    am->amkeytype               = InvalidOid;
#if PG_VERSION_NUM >= 180000
    am->amcanhash            = false;
    am->amconsistentequality = false;
    am->amconsistentordering = false;
#endif

    am->ambuild                = chdb_search_ambuild;
    am->ambuildempty           = chdb_search_ambuildempty;
    am->aminsert               = chdb_search_aminsert;
    am->aminsertcleanup        = NULL;
    am->ambulkdelete           = chdb_search_ambulkdelete;
    am->amvacuumcleanup        = chdb_search_amvacuumcleanup;
    am->amcanreturn            = NULL;
    am->amcostestimate         = chdb_search_costestimate;
    am->amoptions              = chdb_search_amoptions;
    am->amproperty             = NULL;
    am->ambuildphasename       = NULL;
    am->amvalidate             = chdb_search_validate;
    am->amadjustmembers        = NULL;
    am->ambeginscan            = chdb_search_ambeginscan;
    am->amrescan               = chdb_search_amrescan;
    am->amgettuple             = chdb_search_amgettuple;
    am->amgetbitmap            = chdb_search_amgetbitmap;
    am->amendscan              = chdb_search_amendscan;
    am->ammarkpos              = NULL;
    am->amrestrpos             = NULL;
    am->amestimateparallelscan = NULL;
    am->aminitparallelscan     = NULL;
    am->amparallelrescan       = NULL;
#if PG_VERSION_NUM >= 180000
    am->amgettreeheight     = NULL;
    am->amtranslatestrategy = NULL;
    am->amtranslatecmptype  = NULL;
#endif

    PG_RETURN_POINTER(am);
}
