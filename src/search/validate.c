/*
 * Validates an operator class: the options support function, which decides
 * the kind of the family's columns (see ddl.c), chdb_vector's support
 * function, boolean search operators with the strategies of that kind (1..4
 * for text, 1..3 for text arrays, 11..15 for comparisons), and float8
 * ordering operators. The columnar_ops class is declared for anyelement, its
 * operators of concrete types live in its family, so only the family is
 * checked for contents.
 */
bool
chdb_search_validate(Oid opclassoid) {
    bool result = true;
    HeapTuple classtup;
    Form_pg_opclass classform;
    Oid opfamilyoid, opcintype;
    char *opclassname, *opfamilyname;
    CatCList *proclist, *oprlist;

    classtup = SearchSysCache1(CLAOID, ObjectIdGetDatum(opclassoid));
    if (!HeapTupleIsValid(classtup)) {
        elog(ERROR, "cache lookup failed for operator class %u", opclassoid);
    }
    classform    = (Form_pg_opclass)GETSTRUCT(classtup);
    opfamilyoid  = classform->opcfamily;
    opcintype    = classform->opcintype;
    opclassname  = pstrdup(NameStr(classform->opcname));
    opfamilyname = get_opfamily_name(opfamilyoid, false);

    oprlist  = SearchSysCacheList1(AMOPSTRATEGY, ObjectIdGetDatum(opfamilyoid));
    proclist = SearchSysCacheList1(AMPROCNUM, ObjectIdGetDatum(opfamilyoid));

    /* The class's own support function names the kind; any other one will do. */
    ChdbColumnKind kind = CHDB_COL_COLUMNAR;
    bool own_kind       = false;

    for (int i = 0; i < proclist->n_members; i++) {
        Form_pg_amproc procform =
            (Form_pg_amproc)GETSTRUCT(&proclist->members[i]->tuple);

        if (procform->amprocnum == 1 && !own_kind) {
            kind     = chdb_search_proc_kind(procform->amproc);
            own_kind = procform->amproclefttype == opcintype;
        }
        /* chdb_vector's: a strategy in, a function name or a SETTINGS clause out. */
        if (procform->amprocnum == CHDB_VECTOR_PROC_DISTANCE_NAME ||
            procform->amprocnum == CHDB_VECTOR_PROC_QUERY_SETTINGS) {
            if (!check_amproc_signature(
                    procform->amproc, TEXTOID, true, 1, 1, INT2OID
                )) {
                ereport(
                    INFO,
                    errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                    errmsg(
                        "chdb opfamily %s contains function %s with wrong signature "
                        "for support number %d",
                        opfamilyname,
                        format_procedure(procform->amproc),
                        procform->amprocnum
                    )
                );
                result = false;
            }
            continue;
        }
        if (procform->amprocnum != 1) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains function %s with invalid support number "
                    "%d",
                    opfamilyname,
                    format_procedure(procform->amproc),
                    procform->amprocnum
                )
            );
            result = false;
        } else if (
            procform->amproclefttype == opcintype &&
            !check_amoptsproc_signature(procform->amproc)
        ) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains function %s with wrong signature for "
                    "support number 1",
                    opfamilyname,
                    format_procedure(procform->amproc)
                )
            );
            result = false;
        }
    }

    for (int i = 0; i < oprlist->n_members; i++) {
        Form_pg_amop oprform = (Form_pg_amop)GETSTRUCT(&oprlist->members[i]->tuple);
        bool ordering        = oprform->amoppurpose == AMOP_ORDER;
        int strategy         = oprform->amopstrategy;
        int lo = 1, hi = CHDB_ORDER_L1;

        if (!ordering && kind == CHDB_COL_COLUMNAR) {
            lo = CHDB_STRATEGY_EQ;
            hi = CHDB_STRATEGY_GE;
        } else if (!ordering) {
            hi = kind == CHDB_COL_TEXT ? CHDB_STRATEGY_HAS_PHRASE
                                       : CHDB_STRATEGY_HAS_TOKEN;
        }
        if (strategy < lo || strategy > hi) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                strategy <= CHDB_STRATEGY_HAS_PHRASE && kind == CHDB_COL_COLUMNAR
                    ? errmsg(
                          "chdb opfamily %s contains text search operator %s without "
                          "text options as support function 1",
                          opfamilyname,
                          format_operator(oprform->amopopr)
                      )
                    : errmsg(
                          "chdb opfamily %s contains operator %s with invalid strategy "
                          "number %d",
                          opfamilyname,
                          format_operator(oprform->amopopr),
                          strategy
                      )
            );
            result = false;
        }
        if (!ordering && kind != CHDB_COL_COLUMNAR &&
            oprform->amoprighttype != TEXTOID) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains text search operator %s whose right "
                    "type is not text",
                    opfamilyname,
                    format_operator(oprform->amopopr)
                )
            );
            result = false;
        }
        if (ordering != OidIsValid(oprform->amopsortfamily)) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains invalid ORDER BY specification for "
                    "operator %s",
                    opfamilyname,
                    format_operator(oprform->amopopr)
                )
            );
            result = false;
        }
        if (!check_amop_signature(
                oprform->amopopr,
                ordering ? FLOAT8OID : BOOLOID,
                oprform->amoplefttype,
                oprform->amoprighttype
            )) {
            ereport(
                INFO,
                errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
                errmsg(
                    "chdb opfamily %s contains operator %s with wrong signature",
                    opfamilyname,
                    format_operator(oprform->amopopr)
                )
            );
            result = false;
        }
    }

    if (oprlist->n_members == 0) {
        ereport(
            INFO,
            errcode(ERRCODE_INVALID_OBJECT_DEFINITION),
            errmsg("chdb operator class %s has no operators in its family", opclassname)
        );
        result = false;
    }

    ReleaseCatCacheList(proclist);
    ReleaseCatCacheList(oprlist);
    ReleaseSysCache(classtup);
    return result;
}
